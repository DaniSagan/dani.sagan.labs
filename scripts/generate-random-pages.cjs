// Keep the welcome page independent of article components and lazy feature modules.
const fs = require('node:fs');
const ts = require('typescript');
const { inventory } = require('./test-article-navigation.cjs');
const target = 'src/app/home/home-article/random-pages.ts';
function featureRoutes(section) {
  const file = 'src/app/' + section + '/' + section + '-routing.module.ts';
  const tree = ts.createSourceFile(file, fs.readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true);
  const routes = [];
  function visit(node) {
    if (ts.isObjectLiteralExpression(node)) {
      const properties = new Map(node.properties.filter(ts.isPropertyAssignment).map(p => [p.name.getText(tree), p.initializer]));
      const path = properties.get('path');
      if (path && ts.isStringLiteral(path) && path.text && path.text !== '**' && !properties.has('redirectTo') && (properties.has('component') || properties.has('loadComponent'))) routes.push('/' + section + '/' + path.text);
    }
    ts.forEachChild(node, visit);
  }
  visit(tree);
  return routes;
}
const routes = [...new Set([
  ...inventory().routed.filter(r => r.path !== 'test-article').map(r => '/articles/' + r.path),
  ...featureRoutes('tools'), ...featureRoutes('games'),
])].sort();
const content = '// Generated by scripts/generate-random-pages.cjs from registered routes.\n' +
  '// Regenerated before npm start, npm run build and npm run watch.\n' +
  'export const RANDOM_PAGE_ROUTES: readonly string[] = ' + JSON.stringify(routes, null, 2) + ';\n';
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) throw Error('Random page routes are stale: run npm run generate:random-pages');
} else if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) fs.writeFileSync(target, content);
console.log('Random discovery: ' + routes.length + ' registered articles, tools and games; no redirects or test page.');
